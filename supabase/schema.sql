-- VibeCheck schema. Run in Supabase Dashboard > SQL Editor.

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default timezone('utc', now()),
  message text not null check (char_length(message) between 1 and 280)
);

-- Row Level Security: anyone can read and post, nobody can edit or delete.
alter table public.feedback enable row level security;

create policy "Anyone can read feedback"
  on public.feedback for select
  to anon, authenticated
  using (true);

create policy "Anyone can post feedback"
  on public.feedback for insert
  to anon, authenticated
  with check (char_length(message) between 1 and 280);

-- Turn on Realtime for this table.
alter publication supabase_realtime add table public.feedback;
